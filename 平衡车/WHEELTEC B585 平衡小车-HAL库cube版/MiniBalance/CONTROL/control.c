/**************************************************************************
Function: Bluetooth sequence control (improved)
Input   : none
Output  : none
Description: In BT mode, send 'I' to trigger rectangle path:
             Forward 1.2m ?? Turn 90 ?? Forward 0.8m ?? Turn 90
             ?? Forward 1.2m ?? Turn 90 ?? Forward 0.8m ?? Turn 90 ?? Stop
             
Improvements over original:
- Heading hold during straight: uses DMP Yaw for course correction
- Turn uses absolute DMP Yaw angle instead of gyro integration
- Deceleration when approaching distance/angle targets
**************************************************************************/
void Bluetooth_Sequence(void)
{
	static u8  bt_state = 0;           // 0:idle  1:forward  2:turning  3:done
	static u8  bt_step = 0;            // rectangle side index: 0=1.2m, 1=0.8m, 2=1.2m, 3=0.8m
	static float bt_encoder_sum = 0;   // accumulated encoder ticks
	static float bt_target_yaw = 0;    // target DMP heading (0-360), locked at start of each straight
	static float bt_last_yaw_err = 0;  // for heading D-term
	static const float bt_distance[4] = {1200.0f, 800.0f, 1200.0f, 800.0f};
#define DIST_CALIB      0.91f   // encoder calibration
#define BT_HEADING_KP   60.0f   // heading hold P gain
#define BT_HEADING_KD   15.0f   // heading hold D gain
#define BT_DECEL_DIST   250.0f  // mm before target to start decelerating
#define BT_DECEL_ANGLE  25.0f   // degrees before target to start turn deceleration
#define BT_MIN_SPEED     80.0f  // min forward speed during deceleration
#define BT_TURN_SPEED   700.0f  // max turn speed
#define BT_TURN_MIN      150.0f // min turn speed during deceleration
	
	float bt_yaw_error, bt_angle_remain, bt_dist_now, bt_dist_target;
	
	if(Mode != Bluetooth_Mode)
	{
		bt_state = 0;
		bt_step = 0;
		bt_encoder_sum = 0;
		bt_target_yaw = 0;
		bt_last_yaw_err = 0;
		return;
	}
	
	switch(bt_state)
	{
		case 0:  // Idle, waiting for 'I' (0x49) trigger
			bt_encoder_sum = 0;
			bt_step = 0;
			bt_last_yaw_err = 0;
			Move_X = 0;
			Move_Z = 0;
			if(Usart3_Receive == 'I')
			{
				bt_target_yaw = Yaw;   // lock heading now for straight-line hold
				bt_state = 1;
				Usart3_Receive = 0;
			}
			break;
			
		case 1:  // Forward with heading hold + distance deceleration
			// compute current travelled distance
			bt_dist_now = bt_encoder_sum / EncoderMultiples / Encoder_precision 
			              / Reduction_Ratio * Perimeter;
			bt_dist_target = bt_distance[bt_step] * DIST_CALIB;
			
			// distance-based deceleration
			if(bt_dist_target - bt_dist_now > BT_DECEL_DIST)
				Move_X = 300.0f;
			else if(bt_dist_target - bt_dist_now > 0)
				Move_X = BT_MIN_SPEED + (300.0f - BT_MIN_SPEED) 
				         * (bt_dist_target - bt_dist_now) / BT_DECEL_DIST;
			else
				Move_X = 0;
			
			// heading hold: compute yaw error with 0/360 wrap handling
			bt_yaw_error = bt_target_yaw - Yaw;
			if(bt_yaw_error > 180.0f)  bt_yaw_error -= 360.0f;
			if(bt_yaw_error < -180.0f) bt_yaw_error += 360.0f;
			
			// PD correction for heading: Move_Z fed directly into Turn PD
			Move_Z = BT_HEADING_KP * bt_yaw_error 
			         + BT_HEADING_KD * (bt_yaw_error - bt_last_yaw_err);
			bt_last_yaw_err = bt_yaw_error;
			
			// accumulate encoder distance
			bt_encoder_sum += (float)(myabs(Encoder_Left) + myabs(Encoder_Right)) / 2.0f;
			
			if(bt_dist_now >= bt_dist_target)
			{
				bt_encoder_sum = 0;
				// set target yaw for next side: +90 degrees (right turn)
				bt_target_yaw += 90.0f;
				if(bt_target_yaw >= 360.0f) bt_target_yaw -= 360.0f;
				bt_last_yaw_err = 0;
				bt_state = 2;
			}
			break;
			
		case 2:  // Turn right 90 degrees with absolute Yaw + deceleration
			// compute remaining angle using absolute DMP Yaw
			bt_angle_remain = bt_target_yaw - Yaw;
			if(bt_angle_remain > 180.0f)  bt_angle_remain -= 360.0f;
			if(bt_angle_remain < -180.0f) bt_angle_remain += 360.0f;
			
			Move_X = 0;
			
			// decelerate as approaching target angle
			if(fabsf(bt_angle_remain) > BT_DECEL_ANGLE)
				Move_Z = BT_TURN_SPEED;
			else
				Move_Z = BT_TURN_MIN + (BT_TURN_SPEED - BT_TURN_MIN) 
				         * fabsf(bt_angle_remain) / BT_DECEL_ANGLE;
			
			if(fabsf(bt_angle_remain) < 1.5f)  // arrived within 1.5 degrees
			{
				bt_step++;
				bt_last_yaw_err = 0;
				if(bt_step >= 4)
				{
					bt_state = 3;
					bt_step = 0;
				}
				else
				{
					bt_state = 1;
				}
				Move_Z = 0;
			}
			break;
			
		case 3:  // Done, send 'I' again to repeat
			Move_X = 0;
			Move_Z = 0;
			if(Usart3_Receive == 'I')
			{
				bt_target_yaw = Yaw;   // re-lock heading
				bt_state = 1;
				bt_step = 0;
				bt_encoder_sum = 0;
				bt_last_yaw_err = 0;
				Usart3_Receive = 0;
			}
			break;
	}
}

