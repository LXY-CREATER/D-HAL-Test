/**************************************************************************
Function: Heading hold (Kalman fusion + PD controller)
Output  : Move_Z correction value
???????????????????????????+IMU Yaw??PD????
**************************************************************************/
float Keep(void *kf_ptr, float *target_yaw, u8 *locked, float *gyro_lpf, float Q, float R)
{
    Kalman_Yaw_t *kf = (Kalman_Yaw_t *)kf_ptr;
    *gyro_lpf = *gyro_lpf * 0.5f + Gyro_Turn * 0.5f;
    float gyro_dps = *gyro_lpf / 16.4f;
    if (gyro_dps > -0.08f && gyro_dps < 0.08f) gyro_dps = 0;

    float yaw_rate_enc = (Velocity_Right - Velocity_Left) / WHEEL_BASE * 180.0f / PI;
    float fused_yaw = Kalman_Yaw_Update(kf, Yaw, yaw_rate_enc, 0.005f);

    if (!(*locked)) {
        *target_yaw = fused_yaw;
        *locked = 1;
    }

    float yaw_err = fused_yaw - *target_yaw;
    if (yaw_err > 180.0f)  yaw_err -= 360.0f;
    if (yaw_err < -180.0f) yaw_err += 360.0f;

    float correction = (gyro_dps * Yaw_Kd + yaw_err * Yaw_Kp) * HDG_SIGN;

    if (correction > (float)Yaw_Limit)  correction = (float)Yaw_Limit;
    if (correction < -(float)Yaw_Limit) correction = -(float)Yaw_Limit;

    return correction;
}

