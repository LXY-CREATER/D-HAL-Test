// ????��???????????
void Encoder_Reset_Position_MM(float position_mm)
{
    // ???��??????��??��??
    if (position_mm < 0) position_mm = 0;
    if (position_mm > PHYSICAL_TRAVEL_RANGE_MM) position_mm = PHYSICAL_TRAVEL_RANGE_MM;
    
    s_encoder.count = (int32_t)(position_mm * s_counts_per_mm);
    s_encoder.position_mm = position_mm;
    
    if (s_encoder.timer) {
        // ??????????????????????
        int32_t hw_count = s_encoder.count;
        if (s_encoder_reverse) {
            hw_count = -hw_count;
        }
        __HAL_TIM_SET_COUNTER(s_encoder.timer, hw_count & 0xFFFF);  // ????16��
    }
    
    g_encoder.position_mm = position_mm;
    g_encoder.position_percent = (position_mm / PHYSICAL_TRAVEL_RANGE_MM) * 100.0f;
}
// ?????????
void Encoder_Reset(void)
{
    s_encoder.count = 0;
    s_encoder.position_mm = 0;
    s_encoder.velocity_mm_s = 0;
    
    if (s_encoder.timer) {
        __HAL_TIM_SET_COUNTER(s_encoder.timer, 0);
    }
    
    g_encoder.position_mm = 0;
    g_encoder.position_percent = 0;
    g_encoder.velocity = 0;
    g_encoder.velocity_mm_per_s = 0;
}

