// ?��???????????????????
void Encoder_Init_Ex(TIM_HandleTypeDef* timer, uint16_t counts_per_rev, float gear_ratio, 
                    float pulley_circumference_mm, float travel_range_mm)
{
    // ??????��????????
    s_encoder.timer = timer;
    s_encoder.count = 0;
    s_encoder.prev_count = 0;
    s_encoder.position_mm = 0;
    s_encoder.velocity_mm_s = 0;
    s_encoder.last_update_time = HAL_GetTick();
    
    s_counts_per_rev = counts_per_rev;
    s_gear_ratio = gear_ratio;
    s_pulley_circumference_mm = pulley_circumference_mm;
    
    
    // ??????????????????????
    s_counts_per_mm = (float)(s_counts_per_rev * s_gear_ratio) / s_pulley_circumference_mm;
    
    // ?????????????????????????
    g_encoder.total_counts = (int32_t)(travel_range_mm * s_counts_per_mm);
    g_encoder.last_count = 0;
    g_encoder.delta_count = 0;
    g_encoder.last_time = HAL_GetTick();
    g_encoder.velocity = 0;
    g_encoder.velocity_mm_per_s = 0;
    g_encoder.position_mm = 0;
    g_encoder.position_percent = 0;
    
    // ????????????
    HAL_TIM_Encoder_Start(timer, TIM_CHANNEL_ALL);
    
    // ???��?????
    __HAL_TIM_SET_COUNTER(timer, 0);
    
    // ??????????????????
    // ???????????????? s_encoder_reverse = 1; ?????????
}

