// ???��?????????
void Encoder_Update(void)
{
    if (s_encoder.timer == NULL) return;
    
    // ??????????
    int32_t current_count = (int32_t)__HAL_TIM_GET_COUNTER(s_encoder.timer);
    
    // ???????????????16��??32��??
    static int32_t last_raw_count = 0;
    int32_t delta = current_count - last_raw_count;
    
    // ????16��???????????16��????????
    if (delta > 32768) {
        delta -= 65536;
    } else if (delta < -32768) {
        delta += 65536;
    }
    
    // ???????????????????delta
    if (s_encoder_reverse) {
        delta = -delta;
    }
    
    s_encoder.count += delta;
    last_raw_count = current_count;
    
    // ???????��??
    s_encoder.position_mm = (float)s_encoder.count / s_counts_per_mm;
    
    // ???��????0??????��????
    if (s_encoder.position_mm < 0) {
        s_encoder.position_mm = 0;
        s_encoder.count = 0;
        // ???????????????0
        if (s_encoder.timer) {
            __HAL_TIM_SET_COUNTER(s_encoder.timer, 0);
            last_raw_count = 0;
        }
    } else if (s_encoder.position_mm > PHYSICAL_TRAVEL_RANGE_MM) {
        s_encoder.position_mm = PHYSICAL_TRAVEL_RANGE_MM;
        s_encoder.count = (int32_t)(PHYSICAL_TRAVEL_RANGE_MM * s_counts_per_mm);
    }
    
    // ???????
    uint32_t current_time = HAL_GetTick();
    uint32_t dt = current_time - s_encoder.last_update_time;
    
    if (dt > 0) {
        float delta_mm = s_encoder.position_mm - (float)s_encoder.prev_count / s_counts_per_mm;
        s_encoder.velocity_mm_s = (delta_mm * 1000.0f) / dt;  // mm/s
    }
    
    s_encoder.prev_count = s_encoder.count;
    s_encoder.last_update_time = current_time;
    
    // ???????????????????????
    g_encoder.last_count = s_encoder.count;
    g_encoder.delta_count = delta;
    g_encoder.last_time = current_time;
    g_encoder.velocity = (int32_t)(delta * 1000 / dt);  // ????/??
    g_encoder.velocity_mm_per_s = s_encoder.velocity_mm_s;
    g_encoder.position_mm = s_encoder.position_mm;
    
    // ???????��?????????????��??
    if (PHYSICAL_TRAVEL_RANGE_MM > 0) {
        g_encoder.position_percent = (g_encoder.position_mm / PHYSICAL_TRAVEL_RANGE_MM) * 100.0f;
        if (g_encoder.position_percent < 0) g_encoder.position_percent = 0;
        if (g_encoder.position_percent > 100) g_encoder.position_percent = 100;
    } else {
        g_encoder.position_percent = 0;
    }
}

