// ?????????????
void Encoder_Set_Reverse(uint8_t reverse)
{
    s_encoder_reverse = reverse;
    
    // ?????????????????????????????
    if (reverse) {
        s_encoder.count = -s_encoder.count;
        if (s_encoder.timer) {
            int32_t current_count = (int32_t)__HAL_TIM_GET_COUNTER(s_encoder.timer);
            __HAL_TIM_SET_COUNTER(s_encoder.timer, -current_count);
        }
    }
}

